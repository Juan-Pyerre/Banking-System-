-- Script de criação das tabelas (banco H2). É executado automaticamente na inicialização do sistema.
-- Pode ser rodado várias vezes: usa CREATE ... IF NOT EXISTS.

CREATE TABLE IF NOT EXISTS cliente (
    id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL
);

CREATE TABLE IF NOT EXISTS conta (
    id                      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id              INT           NOT NULL,
    tipo                    VARCHAR(20)   NOT NULL,
    saldo                   DECIMAL(19,2) NOT NULL,
    status                  VARCHAR(12)   NOT NULL,
    limite_cheque_especial  DECIMAL(19,2) NOT NULL DEFAULT 0,
    limite_diario_saque     DECIMAL(19,2) NOT NULL,
    senha_hash              VARCHAR(100),
    senha_salt              VARCHAR(64),
    transacao_hash          VARCHAR(100),
    transacao_salt          VARCHAR(64),
    tentativas_login        INT           NOT NULL DEFAULT 0,
    CONSTRAINT fk_conta_cliente FOREIGN KEY (cliente_id) REFERENCES cliente (id)
);

CREATE TABLE IF NOT EXISTS transacao (
    seq                    BIGINT GENERATED BY DEFAULT AS IDENTITY,
    protocolo              VARCHAR(36)   NOT NULL PRIMARY KEY,
    conta_id               INT           NOT NULL,
    tipo                   VARCHAR(30)   NOT NULL,
    valor                  DECIMAL(19,2) NOT NULL,
    data_hora              TIMESTAMP     NOT NULL,
    conta_relacionada_id   INT,
    protocolo_relacionado  VARCHAR(36),
    descricao              VARCHAR(200)  NOT NULL,
    CONSTRAINT fk_transacao_conta FOREIGN KEY (conta_id) REFERENCES conta (id)
);

CREATE INDEX IF NOT EXISTS idx_transacao_conta ON transacao (conta_id, data_hora);
CREATE INDEX IF NOT EXISTS idx_transacao_relacionado ON transacao (protocolo_relacionado);
